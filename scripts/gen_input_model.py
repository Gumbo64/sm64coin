#!/usr/bin/env python3
"""Generates pow/sm64pow/src/exact_table.rs from the input-analysis per-context dependence model
(sm64-binds branch input-analysis, inputs/results/model.json; docs/INPUTS.md section 3) and its
action ids (inputs/src/actions.rs, generated from sm64.h). One row per Mario action.
usage: gen_input_model.py <model.json> <actions.rs> > exact_table.rs"""
import json, re, sys
model = json.load(open(sys.argv[1]))["rows"]
acts = {n: int(v, 16) for n, v in re.findall(r'\("(\w+)", (0x[0-9A-Fa-f]+)\)', open(sys.argv[2]).read())}
rows = []
for k, v in model.items():
    if k.startswith("ACT_"):
        a = acts[k]
    elif k.startswith("action "):
        a = int(k.split()[1], 16)
    else:
        continue  # menus, title head, pause/dialog: not an action context
    n = v["needs"]
    rows.append((a, n["atoms"], n["down"], n["pressed"], n["fsa"], n["fsb"], k))
rows.sort()
print("// Generated by scripts/gen_input_model.py from the input-analysis model (docs/INPUTS.md). Do not edit.")
print("// (action id, stick atoms consumed, button levels consumed, press edges consumed, framesSinceA, framesSinceB)")
print("pub const ROWS: &[(u32, u32, u16, u16, bool, bool)] = &[")
for a, at, d, p, fa, fb, k in rows:
    print(f"    (0x{a:08X}, 0x{at:04X}, 0x{d:04X}, 0x{p:04X}, {str(fa).lower()}, {str(fb).lower()}), // {k}")
print("];")
