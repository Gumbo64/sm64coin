#!/usr/bin/env python3
"""Phase 1 analysis: best run length vs compute from measure_driver.py's results.jsonl.
usage: measure_analyze.py RESULTS.jsonl OUTDIR  -> writes measure_fit.json, measure_tables.md, measure_*.png"""
import json, sys, math, collections
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from scipy.stats import ks_2samp, mannwhitneyu

src, out = sys.argv[1], sys.argv[2]
rows = [json.loads(l) for l in open(src)]
rows = [r for r in rows if r.get("frames") is not None or r.get("status")]
TG = sorted({r["target"] for r in rows if "target" in r})
rng = np.random.default_rng(1)
FPS_NOTE = ""

def by(arm, t):
    return [r for r in rows if r.get("arm") == arm and r.get("target") == t and r["status"] == "found"]

def cpu_per_search(rs):
    # job_cpu is per job (includes all its searches); use per-job average / searches
    jobs = collections.defaultdict(list)
    for r in rs:
        jobs[r["tag"]].append(r)
    tot_cpu = sum(v[0].get("job_cpu") or 0 for v in jobs.values())
    n = sum(len(v) for v in jobs.values())
    return tot_cpu / n if n and tot_cpu else float("nan")

def min_of_n(F, nmax, trials=4000):
    """quantiles of the min of n draws without replacement from the sample F (subsampling)."""
    F = np.asarray(F, float); N = len(F)
    res = {}
    for n in range(1, min(nmax, N) + 1):
        m = np.array([F[rng.choice(N, n, replace=False)].min() for _ in range(trials)])
        res[n] = (m.mean(), *np.quantile(m, [0.1, 0.5, 0.9]))
    return res

def power_floor(C, a, b, fl):
    return a * np.power(C, -b) + fl

summary = {}
md = ["# Measured best run length vs compute (generated by measure_analyze.py)\n"]
fig, axs = plt.subplots(1, max(len(TG), 1), figsize=(5.2 * max(len(TG), 1), 4.4), squeeze=False)
for i, t in enumerate(TG):
    S, G = by("S", t), by("G", t)
    D = [r for r in rows if r.get("arm") == "D" and r.get("target") == t]
    ax = axs[0][i]
    info = {}
    for name, rs in (("S same-template", S), ("G seed-grind", G)):
        if len(rs) < 3:
            continue
        F = np.array([r["frames"] for r in rs], float)
        sim = np.mean([r["sim_frames"] for r in rs])
        cpu = cpu_per_search(rs)
        mon = min_of_n(F, min(len(F) - 1, 40))
        ns = np.array(sorted(mon))
        cm = np.array([mon[n][0] for n in ns]); lo = np.array([mon[n][1] for n in ns]); hi = np.array([mon[n][3] for n in ns])
        ax.plot(ns * sim / 1e6, cm, label=f"{name}: mean of min-of-n (n={len(F)})")
        ax.fill_between(ns * sim / 1e6, lo, hi, alpha=0.15)
        info[name] = dict(n=len(F), F_mean=F.mean(), F_median=float(np.median(F)), F_min=F.min(), F_max=F.max(), F_sd=F.std(), sim_frames_mean=sim, cpu_s_per_search=cpu,
                          curve={int(n): [float(x) for x in mon[n]] for n in ns})
    # deep guided chains
    chains = collections.defaultdict(list)
    for r in D:
        chains[r["tag"]].append(r)
    if chains:
        K = max(len(v) for v in chains.values())
        cum = np.array([[v[k]["cum_sim_frames"] for v in chains.values() if len(v) > k] for k in range(K)], dtype=object)
        bests = [[v[k]["best"] for v in chains.values() if len(v) > k and v[k]["best"]] for k in range(K)]
        cx = [np.mean(c) / 1e6 for c in cum]
        by_ = [np.mean(b) for b in bests]
        ax.plot(cx, by_, "k--o", ms=3, label=f"D guided chain: best so far (mean of {len(chains)} chains)")
        info["D guided"] = dict(chains=len(chains), per_k=[dict(k=k + 1, cum_sim_M=cx[k], best_mean=float(by_[k]), best_all=[int(x) for x in bests[k]]) for k in range(K)])
    ax.set_xscale("log"); ax.set_xlabel("compute: emulated frames (millions)"); ax.set_ylabel("best run length (frames)")
    ax.set_title(f"target {t}"); ax.grid(alpha=0.3); ax.legend(fontsize=6)
    summary[t] = info
    if len(S) >= 5 and len(G) >= 5:
        fs, fg = [r["frames"] for r in S], [r["frames"] for r in G]
        info["S_vs_G"] = dict(ks_p=float(ks_2samp(fs, fg).pvalue), mw_p=float(mannwhitneyu(fs, fg).pvalue), S_mean=float(np.mean(fs)), G_mean=float(np.mean(fg)), S_sd=float(np.std(fs)), G_sd=float(np.std(fg)))
plt.tight_layout(); plt.savefig(f"{out}/measure_curve.png", dpi=130)

# ---- pooled over targets and S+G arms (single-search law is the same within noise), with the guided chains for comparison
allr = [r for r in rows if r.get("arm") in ("S", "G") and r["status"] == "found"]
pooled = None
if len(allr) >= 6:
    Fp = np.array([r["frames"] for r in allr], float)
    simp = float(np.mean([r["sim_frames"] for r in allr]))
    cpup = cpu_per_search(allr)
    mon = min_of_n(Fp, len(Fp) - 1)
    ns = np.array(sorted(mon), float)
    cm = np.array([mon[n][0] for n in ns]); lo = np.array([mon[n][1] for n in ns]); hi = np.array([mon[n][3] for n in ns])
    try:
        pf, _ = curve_fit(power_floor, ns, cm, p0=[cm[0] - cm[-1], 0.7, cm[-1] * 0.9], bounds=([0, 0.01, 0], [1e6, 5, cm.min()]), maxfev=20000)
    except Exception:
        pf = [float("nan")] * 3
    pooled = dict(n=len(Fp), F_mean=float(Fp.mean()), F_median=float(np.median(Fp)), F_sd=float(Fp.std(ddof=1)), F_min=float(Fp.min()), F_max=float(Fp.max()),
                  sim_frames=simp, cpu_s=cpup, fit=dict(a=float(pf[0]), b=float(pf[1]), floor=float(pf[2])), curve={int(n): [float(x) for x in mon[n]] for n in ns})
    fig, ax = plt.subplots(figsize=(6.4, 4.6))
    ax.plot(ns * cpup / 60, cm, "b-o", ms=3, label=f"min of n independent searches (pooled, N={len(Fp)})")
    ax.fill_between(ns * cpup / 60, lo, hi, color="b", alpha=0.15, label="p10-p90 of the min")
    ax.plot(ns * cpup / 60, power_floor(ns, *pf), "k:", label=f"fit {pf[0]:.0f}*n^-{pf[1]:.2f} + {pf[2]:.0f}")
    ax.axhline(pf[2], color="gray", lw=0.6)
    for t, c in zip(TG, ["C1", "C2", "C3"]):
        for r in rows:
            pass
    D = [r for r in rows if r.get("arm") == "D" and r["status"] == "found"]
    for tag in sorted({r["tag"] for r in D}):
        v = [r for r in D if r["tag"] == tag]
        ax.plot([r["cum_sim_frames"] / simp * cpup / 60 for r in v], [r["best"] for r in v], "--s", ms=4, label=f"guided chain {tag}")
    ax.set_xscale("log"); ax.set_xlabel("compute (single-core CPU-minutes; 1 search = %.0f)" % (cpup / 60)); ax.set_ylabel("best run length (frames)"); ax.grid(alpha=0.3); ax.legend(fontsize=7)
    plt.tight_layout(); plt.savefig(f"{out}/measure_curve_pooled.png", dpi=130)
    summary["pooled"] = pooled
    md.append(f"\n## pooled (all targets, S+G arms; N={len(Fp)})\n\nsingle search: mean {Fp.mean():.0f}, median {np.median(Fp):.0f}, sd {Fp.std(ddof=1):.0f}, min {Fp.min():.0f}, max {Fp.max():.0f}; {simp/1e6:.1f} M frames and {cpup:.0f} CPU-s ({cpup/60:.1f} core-min) per search\n\nFit of the mean of the min of n: `L(n) = {pf[0]:.0f} * n^-{pf[1]:.2f} + {pf[2]:.0f}` (bootstrap of {len(Fp)} samples: the floor is only as good as the smallest sample)\n")
    md.append("\n| n searches | CPU-min | mean best | p10 | median | p90 |\n|---|---|---|---|---|---|")
    for n in [1, 2, 4, 8, 12, 16]:
        c = mon.get(n)
        if c: md.append(f"| {n} | {n * cpup / 60:.0f} | {c[0]:.0f} | {c[1]:.0f} | {c[2]:.0f} | {c[3]:.0f} |")

# pooled fit L(C) = a C^-b + floor on the G arm (independent draws) per target, C in units of the target's mean search cost
fits = {}
for t in TG:
    inf = summary[t].get("G seed-grind") or summary[t].get("S same-template")
    if not inf:
        continue
    ns = np.array(sorted(map(int, inf["curve"].keys())), float)
    L = np.array([inf["curve"][int(n)][0] for n in ns])
    try:
        p, _ = curve_fit(power_floor, ns, L, p0=[L[0] - L[-1], 0.5, L[-1] * 0.9], bounds=([0, 0.01, 0], [1e6, 5, L.min()]), maxfev=20000)
        fits[t] = dict(a=p[0], b=p[1], floor=p[2], unit="searches", F1=float(L[0]), L40=float(L[-1]))
    except Exception as e:
        fits[t] = dict(error=str(e))
json.dump(dict(summary=summary, fits=fits), open(f"{out}/measure_fit.json", "w"), indent=1, default=float)
for t in TG:
    md.append(f"\n## target {t}\n")
    for name, inf in summary[t].items():
        if name.startswith(("S", "G")) and "curve" in inf:
            md.append(f"\n**{name}**: n={inf['n']} searches, single-search F mean {inf['F_mean']:.0f} / median {inf['F_median']:.0f} (min {inf['F_min']:.0f}, max {inf['F_max']:.0f}, sd {inf['F_sd']:.0f}); {inf['sim_frames_mean']/1e6:.1f} M sim frames and {inf['cpu_s_per_search']:.0f} CPU-s per search\n")
            md.append("\n| n searches | compute (M frames) | CPU-min | mean best | p10 | median | p90 |\n|---|---|---|---|---|---|---|")
            for n in [1, 2, 4, 8, 16, 32]:
                c = inf["curve"].get(n)
                if c:
                    md.append(f"| {n} | {n * inf['sim_frames_mean'] / 1e6:.0f} | {n * inf['cpu_s_per_search'] / 60:.1f} | {c[0]:.0f} | {c[1]:.0f} | {c[2]:.0f} | {c[3]:.0f} |")
    if "D guided" in summary[t]:
        md.append("\n**D guided chain** (search k guided by the best run so far)\n\n| k | cum compute (M frames) | mean best | all chains |\n|---|---|---|---|")
        for r in summary[t]["D guided"]["per_k"]:
            md.append(f"| {r['k']} | {r['cum_sim_M']:.0f} | {r['best_mean']:.0f} | {r['best_all']} |")
    if "S_vs_G" in summary[t]:
        s = summary[t]["S_vs_G"]; md.append(f"\nS vs G single-search distributions: KS p={s['ks_p']:.3f}, Mann-Whitney p={s['mw_p']:.3f}; mean {s['S_mean']:.0f} vs {s['G_mean']:.0f}; sd {s['S_sd']:.0f} vs {s['G_sd']:.0f}")
    if t in fits:
        md.append(f"\nFit (G arm mean-of-min curve, C in searches): `L(n) = {fits[t].get('a', float('nan')):.0f} * n^-{fits[t].get('b', float('nan')):.2f} + {fits[t].get('floor', float('nan')):.0f}`")
open(f"{out}/measure_tables.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
