#!/usr/bin/env python3
"""Writes perturb/src/sm64_addrs.rs: where the perturbation's inputs live in
each game build's memory, read from the builds' linker maps.

    python3 pow/tools/gen_sm64_addrs.py <sm64-port dir>

Rerun after rebuilding the game (sm64-binds branch sm64coin, `make sm64-build`).
The headless build is what native nodes and miners run; the visual (rendering)
build is what the browser runs. Struct offsets are the same in both.
"""
import os, re, sys

PORT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "..", "sm64-binds", "sm64-port")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "perturb", "src", "sm64_addrs.rs")
SYMS = ["gMarioStates", "gLakituState", "gGlobalTimer", "gRandomSeed16", "gAreaUpdateCounter", "gCurrLevelNum", "gCurrAreaIndex"]
BUILDS = {"HEADLESS": "us_web_headless", "VISUAL": "us_web"}

def addrs(build):
    text = open(os.path.join(PORT, "build", build, "sm64.map")).read()
    out = {}
    for s in SYMS:
        m = re.search(r"^\s+([0-9a-f]+)\s+[0-9a-f]+\s+[0-9a-f]+\s+" + re.escape(s) + r"$", text, re.M)
        if not m:
            sys.exit(f"{s} not found in {build}'s map")
        out[s] = int(m.group(1), 16)
    return out

lines = ["// Generated by pow/tools/gen_sm64_addrs.py from the game builds' linker maps. Don't edit.", ""]
for name, build in BUILDS.items():
    a = addrs(build)
    lines.append(f"pub const {name}: Addrs = Addrs {{")
    for s in SYMS:
        lines.append(f"    {s}: 0x{a[s]:x},")
    lines.append("};")
    lines.append("")
open(OUT, "w").write("\n".join(lines))
print("wrote", OUT)
