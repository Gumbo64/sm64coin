// The proof-of-play blob, as far as the browser needs it. The format belongs
// to pow/sm64pow/src/proof.rs and commit.rs (v0.4): varint(frames) || start || input_hash (32) || codec ||
// body. The browser only writes codec 0 (raw, 4 bytes per frame); the daemon re-encodes
// submitted proofs with its smallest codec (the block id, the committed hash, doesn't change).
// The explorer reads `sm64_pads` from get_block, already decoded to raw. State-aware
// codecs (3+) cannot be decoded without replaying the run, so get_block fills
// `sm64_pads` for them only with sm64_played: true (the Block page does).
import { GamePad } from 'sm64-binds-frontend';
import { hexToBytes, bytesToHex, varint, seal, committedProof, proofId, inputHash } from './block.js';
export { hexToBytes, bytesToHex, seal, committedProof, proofId, inputHash };

/** Raw pads (4 bytes each: buttons u16 LE, stick x i8, stick y i8) -> GamePads. */
export function rawToPads(hex) {
  const b = hexToBytes(hex);
  const pads = [];
  for (let i = 0; i + 4 <= b.length; i += 4) {
    const button = b[i] | (b[i + 1] << 8);
    const sx = b[i + 2] > 127 ? b[i + 2] - 256 : b[i + 2];
    const sy = b[i + 3] > 127 ? b[i + 3] - 256 : b[i + 3];
    pads.push(new GamePad(button, sx, sy));
  }
  return pads;
}

/** A codec-0 proof blob for `pads`. */
export function rawProof(pads) {
  const out = new Uint8Array(1 + pads.length * 4);
  out[0] = 0; // codec id: raw
  pads.forEach((p, i) => {
    const o = 1 + i * 4;
    out[o] = p.button & 0xff;
    out[o + 1] = (p.button >> 8) & 0xff;
    out[o + 2] = p.stick_x & 0xff;
    out[o + 3] = p.stick_y & 0xff;
  });
  return out;
}

/** The committed proof for a run: varint(frames) || start byte (0: from the parent block's end state,
 * 1: from power-on) || input_hash (32) || codec 0 (raw) || the pads of the frames that weren't poked.
 * Pokes are regenerated by the verifier, so they aren't stored (pow/sm64pow/src/commit.rs). The daemon
 * re-encodes it with its smallest codec. */
export function proofFromRun(pads, poked, powerOn = false) {
  const inputs = pads.filter((_, i) => !poked[i]);
  return committedProof(pads.length, powerOn ? 1 : 0, rawProof(inputs).subarray(1));
}

function readVarint(b, i) {
  let n = 0, mul = 1;
  for (;;) {
    const x = b[i++];
    n += (x & 0x7f) * mul;
    if (x < 0x80) return [n, i];
    mul *= 128;
  }
}

/** The template blob with its header timestamp replaced (the header is
 * varint major, varint minor, varint timestamp, prev_id, ...). Used to
 * re-stamp THIS attempt's template at submit time: the time limit depends on
 * the timestamp, while the seed doesn't. */
export function withTimestamp(templateHex, timestamp) {
  const t = hexToBytes(templateHex);
  let [, i] = readVarint(t, 0);
  [, i] = readVarint(t, i);
  const at = i;
  [, i] = readVarint(t, i);
  const ts = varint(timestamp);
  const out = new Uint8Array(t.length - (i - at) + ts.length);
  out.set(t.subarray(0, at), 0);
  out.set(ts, at);
  out.set(t.subarray(i), at + ts.length);
  return bytesToHex(out);
}

/** The header timestamp of a template blob. */
export function templateTimestamp(templateHex) {
  const t = hexToBytes(templateHex);
  let [, i] = readVarint(t, 0);
  [, i] = readVarint(t, i);
  return readVarint(t, i)[0];
}

/** A Mupen64 movie (.m64) of `pads`: 0x400-byte header, then per frame
 * buttons (u16 big-endian), stick x, stick y. */
export function toM64(pads) {
  const out = new Uint8Array(0x400 + pads.length * 4);
  out.set([0x4d, 0x36, 0x34, 0x1a], 0); // "M64\x1a"
  const dv = new DataView(out.buffer);
  dv.setUint32(0x4, 3, true); // version
  dv.setUint32(0x18, pads.length, true); // input samples
  dv.setUint8(0x15, 1); // controllers
  pads.forEach((p, i) => {
    const o = 0x400 + i * 4;
    dv.setUint16(o, p.button, false);
    out[o + 2] = p.stick_x & 0xff;
    out[o + 3] = p.stick_y & 0xff;
  });
  return out;
}

/**
 * A Mupen64(Plus) movie of `pads` (the US ROM, from power-on): the same 4-byte samples as toM64 after a header Mupen
 * accepts (60 VI/s, VI count 2 per sample, start from power-on, controller 1, the ROM's name, CRC1 and country) and
 * one leading empty poll (Mupen reads the first sample one poll before the game's first frame). Checked against
 * Mupen64Plus with the 120-star run (every star on the expected frame).
 */
export function toMupenM64(pads) {
  const n = pads.length + 1;
  const out = new Uint8Array(0x400 + n * 4);
  const dv = new DataView(out.buffer);
  out.set([0x4d, 0x36, 0x34, 0x1a], 0); // "M64\x1a"
  dv.setUint32(0x4, 3, true); // version
  dv.setUint32(0x8, Math.floor(Date.now() / 1000) >>> 0, true); // movie uid
  dv.setUint32(0xC, n * 2, true); // VI count
  dv.setUint32(0x10, 0, true); // rerecords
  out[0x14] = 60; // VI/s
  out[0x15] = 1; // controllers
  dv.setUint32(0x18, n, true); // input samples
  dv.setUint16(0x1C, 2, true); // start from power-on
  dv.setUint32(0x20, 1, true); // controller 1 present
  out.set(new TextEncoder().encode('SUPER MARIO 64'), 0xC4); // ROM internal name
  out.set([0x63, 0x5a, 0x2b, 0xff], 0xE4); // the US ROM's CRC1 (ROM bytes 0x10..0x14)
  dv.setUint16(0xE8, 0x45, true); // country 'E' (US)
  pads.forEach((p, i) => {
    const o = 0x400 + (i + 1) * 4;
    dv.setUint16(o, p.button, false);
    out[o + 2] = p.stick_x & 0xff;
    out[o + 3] = p.stick_y & 0xff;
  });
  return out;
}

export function download(name, bytes, type = 'application/octet-stream') {
  const url = URL.createObjectURL(new Blob([bytes], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
