// The proof-of-play blob, as far as the browser needs it. The format belongs
// to pow/sm64pow/src/proof.rs: the first byte names the codec. The browser
// only writes codec 0 (raw, 4 bytes per frame); the daemon re-encodes
// submitted proofs with its smallest codec (the block id doesn't change).
// The explorer reads `sm64_pads` from get_block, already decoded to raw. State-aware
// codecs (3+) cannot be decoded without replaying the run, so get_block fills
// `sm64_pads` for them only with sm64_played: true (the Block page does).
import { GamePad } from 'sm64-binds-frontend';
import { hexToBytes, bytesToHex, varint, seal } from './block.js';
export { hexToBytes, bytesToHex, seal };

/** Raw pads (4 bytes each: buttons u16 LE, stick x i8, stick y i8) -> GamePads. */
export function rawToPads(hex) {
  const b = hexToBytes(hex);
  const pads = [];
  for (let i = 0; i + 4 <= b.length; i += 4) {
    const button = b[i] | (b[i + 1] << 8);
    const sx = b[i + 2] > 127 ? b[i + 2] - 256 : b[i + 2];
    const sy = b[i + 3] > 127 ? b[i + 3] - 256 : b[i + 3];
    pads.push(new GamePad(button, sx, sy));
  }
  return pads;
}

/** A codec-0 proof blob for `pads`. */
export function rawProof(pads) {
  const out = new Uint8Array(1 + pads.length * 4);
  out[0] = 0; // codec id: raw
  pads.forEach((p, i) => {
    const o = 1 + i * 4;
    out[o] = p.button & 0xff;
    out[o + 1] = (p.button >> 8) & 0xff;
    out[o + 2] = p.stick_x & 0xff;
    out[o + 3] = p.stick_y & 0xff;
  });
  return out;
}

/** The proof for a run: varint(frames) || start byte (0: from the parent
 * block's end state, 1: from power-on) || codec 0 (raw) || the pads of the
 * frames that weren't poked. Pokes are regenerated by the verifier, so they
 * aren't stored (pow/sm64pow/src/proof.rs). The daemon re-encodes it with its
 * smallest codec. */
export function proofFromRun(pads, poked, powerOn = false) {
  const inputs = pads.filter((_, i) => !poked[i]);
  const raw = rawProof(inputs);
  const head = varint(pads.length);
  const out = new Uint8Array(head.length + 1 + raw.length);
  out.set(head, 0);
  out[head.length] = powerOn ? 1 : 0;
  out.set(raw, head.length + 1);
  return out;
}

function readVarint(b, i) {
  let n = 0, mul = 1;
  for (;;) {
    const x = b[i++];
    n += (x & 0x7f) * mul;
    if (x < 0x80) return [n, i];
    mul *= 128;
  }
}

/** The template blob with its header timestamp replaced (the header is
 * varint major, varint minor, varint timestamp, prev_id, ...). Used to
 * re-stamp THIS attempt's template at submit time: the time limit depends on
 * the timestamp, while the seed doesn't. */
export function withTimestamp(templateHex, timestamp) {
  const t = hexToBytes(templateHex);
  let [, i] = readVarint(t, 0);
  [, i] = readVarint(t, i);
  const at = i;
  [, i] = readVarint(t, i);
  const ts = varint(timestamp);
  const out = new Uint8Array(t.length - (i - at) + ts.length);
  out.set(t.subarray(0, at), 0);
  out.set(ts, at);
  out.set(t.subarray(i), at + ts.length);
  return bytesToHex(out);
}

/** The header timestamp of a template blob. */
export function templateTimestamp(templateHex) {
  const t = hexToBytes(templateHex);
  let [, i] = readVarint(t, 0);
  [, i] = readVarint(t, i);
  return readVarint(t, i)[0];
}

/** A Mupen64 movie (.m64) of `pads`: 0x400-byte header, then per frame
 * buttons (u16 big-endian), stick x, stick y. */
export function toM64(pads) {
  const out = new Uint8Array(0x400 + pads.length * 4);
  out.set([0x4d, 0x36, 0x34, 0x1a], 0); // "M64\x1a"
  const dv = new DataView(out.buffer);
  dv.setUint32(0x4, 3, true); // version
  dv.setUint32(0x18, pads.length, true); // input samples
  dv.setUint8(0x15, 1); // controllers
  pads.forEach((p, i) => {
    const o = 0x400 + i * 4;
    dv.setUint16(o, p.button, false);
    out[o + 2] = p.stick_x & 0xff;
    out[o + 3] = p.stick_y & 0xff;
  });
  return out;
}

export function download(name, bytes, type = 'application/octet-stream') {
  const url = URL.createObjectURL(new Blob([bytes], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
